import React, { createRef, useContext, useEffect, useState } from "react"
import { ContextMenuContext, ContextMenuOptions, contextMenuPropagation } from "../../../Desktop/Contexts/ContextMenuContext"
import { AppRunningID, RunningAppsContext } from "../../../Desktop/Contexts/RunningAppsContext"
import { MediaControllerProps } from "../../MediaController/MediaController"
import "./VideoMedia.css"
import { TooltipContext } from "../../../Desktop/Contexts/TooltipContext"


// Typing for VideoMedia Props
// Only takes the `data` property from `MyFileSystemFile`
type VideoMediaProps = AppRunningID & {
    fileContentData: string
}

////// These three typings are related for the colour swaping feature
////// The three typings work in unison with one another 
// Typing to represent a single pixel value
// Holds information about the pixels RGBA values
type RGBAValue = {
    red: number ,
    green: number,
    blue: number,
    alpha: number
}

// The typing for a single Colour Swap Value
// Holds information for:
    // The RGBA value to be swapped ('from')
    // The RGBA value to swap with ('to')
    // The threshold range a pixel must be from the 'from' RGBA value to be valid for swapping ('range') 
type ColourSwapValue = {
    from: RGBAValue,
    to: RGBAValue,
    range: number
}

// The typing for the object that holds all colour swap values
// Holds information for:
    // The Colour Swap Values to be checked @ each frame ('values')
    // A list of all pixels that have been swapped @ each frame ('changedPixels')
        // This list is designed to be reset each time the frame changes, and before colour swaps are applied
type ColourSwapList = {
    values: ColourSwapValue[],
    changedPixels: React.MutableRefObject<Set<number> | null>
}
//////---------------------------------------

// The typing to hold all the additional properties that the user can interact with
// This is meant to hold any values that alter the original playback of the video
// Holds information for:
    // Video's playback rate ('playbackRate')
    // Video's ability to preserve pitch with an altered playback rate ('preservesPitch')
    // Video's colour swap list ('colourSwapList')
    // To display the video in grayscale, applied after colour swap list ('grayscale')
    // To inverse the videos colours, applied after colour swap list and grayscale ('inverseColour')
type VideoCustomOptions = {
    playbackRate: number,
    preservesPitch: boolean,
    colourSwapList: ColourSwapList,
    grayscale: boolean,
    inverseColour: boolean
}


// Typing holds all the ref values that are used by VideoMedia
// Holds information for:
    // Reference for the <video> tag ('videoRef')
    // Reference for the <canvas> tag ('canvasRef')
    // Reference for the seekbar <div> ('seekbarRef')
    // Reference for the loop ID, generated by requestAnimationFrame, used to update the 'currentTime' property in 'videoProperties' ('currentTimeUpdateRef')
type RefCollection = {
    videoRef: React.MutableRefObject<HTMLVideoElement | null>,
    canvasRef: React.MutableRefObject<HTMLCanvasElement | null>,
    seekBarRef: React.MutableRefObject<HTMLDivElement | null>,
    currentTimeUpdateRef: React.MutableRefObject<number | null>,
}

// Typing holds all the properties that the video can have
// Holds information for:
    // Whether the video is currently playing or not ('playing')
        // This property is set when the <video> media play/pause event is invoked
    // The current time elapsed by the video ('currentTime')
    // The current percentage of the video that has elapsed ('currentTimePercentage')
    // Whether to have the video auto-loop or not ('loop')
    // Whether to stretch/fill the video into the full window width and height ('videoFill')
    // Whether or not the seekbar is currently being clicked on or not ('seekBarClicked')
    // The collection of all the refs used by the video ('refCollection')
    // The video's current custom option values ('VideoCustomOptions')
type VideoProperties = {
    playing: boolean,
    currentTime: number,
    currentTimePercentage: number,
    loop: boolean,
    videoFill: boolean
    seekBarClicked:boolean,
    refCollection: RefCollection,
    videoCustomOptions: VideoCustomOptions
}


// Typing that identifies all video properties that can be updated
// This is used to help identify which properties can be manipulated by the MediaController
// Helps when autofill/autocomplete
export type VideoUpdatableOptions = VideoCustomOptions & {
    playing:boolean,
    currentTime: number
}

// Typing used by the overlay 
// Holds information for:
    // Whether to display the overlay or not ('display')
    // The ID of the timeout used to auto-hide the overlay when no mouse movement is detected over the video ('timeoutID')
type OverlayProperties = {
    display: boolean,
    timeoutID: React.MutableRefObject<number | null>
}


/**
 * Main handler for "VIDEO" file types 
 * @param props Requires the `data` property from `MyFileSystemFile`
 * @returns Component
 */
export function VideoMedia ({app_running_id, fileContentData}:VideoMediaProps) {
    // State for the current video properties
    const [videoProperties, setVideoProperties] = useState<VideoProperties>({
        playing: true,
        currentTime: 0,
        currentTimePercentage: 0,
        loop: false,
        videoFill: true,
        seekBarClicked: false,
        refCollection: {
            videoRef:createRef<HTMLVideoElement>(), 
            canvasRef:createRef<HTMLCanvasElement>(),
            seekBarRef: createRef<HTMLDivElement>(),
            currentTimeUpdateRef: createRef<number|null>()
        },
        videoCustomOptions: {
            playbackRate: 1,
            preservesPitch: true,
            grayscale: false,
            inverseColour: false,
            colourSwapList: {
                values: [],
                changedPixels: createRef<Set<number>>()
            }
        }
    })

    // State for holding the app running ID for its relatead media controller
    const [controllerAppRunningID, setControllerAppRunningID] = useState<string>("")

    // State data for the overlay and its properties
    const [showOverlay, setShowOverlay] = useState<OverlayProperties>({display:false, timeoutID: createRef<number|null>()})

    // Used to create a context menu when right clicking the canvas
    const {contextMenuData,contextMenuDispatch} = useContext(ContextMenuContext)

    // Used for two main purposes
        // Used to handle the related media controller (open/create, close/delete, and focus)
        // Used to maximize the VideoMedia window when double clicking the canvas
    const {runningAppsDispatch} = useContext(RunningAppsContext)

    // Used to create tooltips on overlay buttons
    const {tooltipDispatch} = useContext(TooltipContext)


    // Used when component is first mounted and unmounted
    useEffect(()=>{
        // On mount, create the set used to hold all changed pixels
        videoProperties.videoCustomOptions.colourSwapList.changedPixels.current = new Set<number>()

        // On dismount, cancel the loop that updates updates the 'currentTime' property
        return () =>{
                cancelAnimationFrame(videoProperties.refCollection.currentTimeUpdateRef.current!)
        }
    },[])

    // Used on component unmount (ie. when video app is closed), handles the video's media controller
    useEffect(()=>{
        return () => {
            // If there is currently a Media Controller open for the video
            if (controllerAppRunningID != ""){
                // Close the Media Controller, so that there isn't a Media Controller open for a video that is closed
                runningAppsDispatch({
                    type:"DELETE",
                    app_running_id: controllerAppRunningID
                })
            }
        }
    },[controllerAppRunningID, runningAppsDispatch])

    
    // Used anytime the video's 'playing' property is changed
    useEffect(()=>{

        // The main loop that handles updating the 'currentTime' video property
        // Loop updates the 'currentTime' property before restarting the loop (with the new loop ID being stored in 'currentTimeUpdateRef')
        const updateCurrentTimeLoop = () =>{
            setVideoProperties(pendingState =>({...pendingState, currentTime: pendingState.refCollection.videoRef.current!.currentTime}))
            videoProperties.refCollection.currentTimeUpdateRef.current = requestAnimationFrame(updateCurrentTimeLoop)
        }

        // Handles what to do based on the video's current state
        if (videoProperties.refCollection.videoRef.current){
            // If the video is currently playing
            if (videoProperties.playing){

                // Start the loop to constantly update 'currentTime'
                videoProperties.refCollection.currentTimeUpdateRef.current = requestAnimationFrame(updateCurrentTimeLoop)

            }
            // If the video is currently paused
            else{
                // Cancel the loop that updates the app's 'currentTime'
                cancelAnimationFrame(videoProperties.refCollection.currentTimeUpdateRef.current!)
                // Set the ID for the loop to 'null'
                videoProperties.refCollection.currentTimeUpdateRef.current = null
            }
        }
    },[videoProperties.playing])


    // Used anytime the video's 'currentTime' property is changed
    useEffect(()=>{
        // Render the current frame
        requestAnimationFrame(renderFrame)
        // Update the size of the seek bar progress
        setVideoProperties(pendingProperties => ({...pendingProperties, currentTimePercentage: calculateProgressPercentage()}))
    },[videoProperties.currentTime])

    // Used anytime the video's 'videoCustomOptions' property is changed
    useEffect(()=>{
        // If the video isn't playing 
        if (!videoProperties.playing){
            // Rerender the frame
            // This is done because if the video isn't playing, then 'currentTime' isn't being updated, and thus 'renderFrame' isn't called
            requestAnimationFrame(renderFrame)
        }
    },[videoProperties.videoCustomOptions])


    /**
     * Function that handles rendering the video from the `<video> `tag into the <canvas> tag
     * 
     * Also handles applying visual transformations to the video frame before rendering it into the canvas
     */
    function renderFrame(){
        //Check if videoRef and canvasRef are available
        if (videoProperties.refCollection.videoRef.current != null && videoProperties.refCollection.canvasRef.current != null && videoProperties.videoCustomOptions.colourSwapList.changedPixels.current != null ){
            videoProperties.videoCustomOptions.colourSwapList.changedPixels.current.clear()

            
            //Store context for canvas 
            const canvasContext = videoProperties.refCollection.canvasRef.current.getContext("2d")! 

            // Paint canvas with frame from video player
            canvasContext.drawImage(
                videoProperties.refCollection.videoRef.current, 
                0,
                0, 
                videoProperties.refCollection.canvasRef.current.width, 
                videoProperties.refCollection.canvasRef.current.height 
            )

            // Grab frame information from canvas (which now holds the unalted frame from the video player)
            const videoFrame = canvasContext.getImageData(
                0,
                0,
                videoProperties.refCollection.canvasRef.current.width, 
                videoProperties.refCollection.canvasRef.current.height
            )

            // Determine the amount of pixels in the frame
            // In videoFrame.data, it stores pixel data from top left -> bottom right in an array
            // Each index in the array is either a R,G,B, or A value
            // The data is supposed to be viewed in groups of 4, so that neighbouring indexes represent the same pixel
            // So, by dividing the length of the data by 4, we can count the total pixels in the frame
            const totalPixels = videoFrame.data.length/4

            // For each pixel, perform visual changes
            for (let currentPixel=0; currentPixel< totalPixels; currentPixel++){
                
                // Since totalPixel represents the totalLength/4, currentPixel does not represent the index of the pixel in the array
                // To find the index of the pixel in the array, we just take the currentPixel and multiply it by 4
                // This leads us to the starting index for the current pixel
                const currentPixelIndex = currentPixel*4

                // The element at the currentPixelIndex represents red, then green, then blue, and then finally alpha
                // Store the values as a non-constants so that we can apply manipulations before reinserting them back into the array

                let red = videoFrame.data[currentPixelIndex + 0]
                let green = videoFrame.data[currentPixelIndex + 1]
                let blue = videoFrame.data[currentPixelIndex + 2]
                // let alpha = videoFrame.data[i*4 + 3] commented out.... FOR NOW

                //// Logic for colour swapping
                // For each of the colour swap values
                for (const colourSwapValue of videoProperties.videoCustomOptions.colourSwapList.values){
                    // Calculate the differences between the R,G, and B values for the currentPixel and the current colourSwapValue
                    const redDiff = Math.abs(colourSwapValue.from.red - red)
                    const greenDiff = Math.abs(colourSwapValue.from.green - green)
                    const blueDiff = Math.abs(colourSwapValue.from.blue - blue)

                    // Check if the differences between the R,G, and B values fall within the range threshold of the current colourSwapValue
                    const redCheck = redDiff >=0 && redDiff <= colourSwapValue.range
                    const greenCheck = greenDiff >=0 && greenDiff <= colourSwapValue.range
                    const blueCheck = blueDiff >=0 && blueDiff <= colourSwapValue.range

                    // If all 3 differences fall within the range threshold, the current pixel is valid to be swapped
                    if (redCheck && greenCheck && blueCheck){
                        // First add the current pixel (not the index of the current pixel) to the 'changedPixels' list
                        videoProperties.videoCustomOptions.colourSwapList.changedPixels.current.add(currentPixel)
                        // Update RGB values to the values in the current colourSwapValue
                        red = colourSwapValue.to.red
                        green = colourSwapValue.to.green
                        blue = colourSwapValue.to.blue
                    }
   
                }

                // Applies grayscale transformation
                if (videoProperties.videoCustomOptions.grayscale){
                    // Computes the 'gray' for the pixel and applys it to the RGB variables
                    const grey = (red + green + blue) /3;
                    red = green = blue = grey;

                }

                // Applies inverse colour transformation
                if (videoProperties.videoCustomOptions.inverseColour){
                    // Inverts the RGB values and applys it to the RGB variables
                    red = 255 - red;
                    green = 255 - green;
                    blue = 255 - blue;
                }

                // Reinsert RGB values back into the array, where the original values are stored
                videoFrame.data[currentPixelIndex + 0] = red;
                videoFrame.data[currentPixelIndex + 1] = green;
                videoFrame.data[currentPixelIndex + 2] = blue;
            }

            //Apply transformed video frame to canvas
            canvasContext.putImageData(videoFrame, 0, 0);
        }
    }

    /**
     * Function for calculating the percentage the video has elapsed
     * @returns The percent value that the video has elapsed
     */
    function calculateProgressPercentage():number{
        if (videoProperties.refCollection.videoRef.current != null && !isNaN(videoProperties.refCollection.videoRef.current.duration) && videoProperties.refCollection.seekBarRef.current != null){
            return ((videoProperties.refCollection.videoRef.current.currentTime /(videoProperties.refCollection.videoRef.current.duration)))
        } else {return 0}
    }


    /**
     * Updates both `videoProperties.currentTime` and the video's current time (`videoRef.current.currentTime`) in a single function
     * 
     * Purpose of the function is to streamline updating process for currentTime
     * @param newTime The new time the set the video to
     */
    function updateCurrentTime(newTime:number){
        setVideoProperties(pendingState =>({...pendingState, currentTime: newTime}))
        videoProperties.refCollection.videoRef.current!.currentTime = newTime
    }

    /**
     * Restarts the video
     * 
     * Function just sets the video's currentTime to 0 before playing the video
     */
    function restartVideo(){
        updateCurrentTime(0)
        videoProperties.refCollection.videoRef.current!.play()
    }


    /**
     * Handler for when the seekbar is clicked or when the mouse is moved while the seekbar is clicked on
     * 
     * Based on the position of the mouse within the (or in relation to) the seekbar, update the `currentTime` of the `<video>` element
     * 
     * @example "If the mouse is click on (or dragged to) the middle of the progress bar, the video should jump to the middle of it's duration"
     * 
     * @param event `MouseEvent` from `onMouseDown` and `onMouseMove`
     */
    function videoScrubbing(event: React.MouseEvent<HTMLDivElement, MouseEvent> | MouseEvent ){
        // Grab location and sizing data of the seekbar
        const seekBarBoundingClientRect:DOMRect = videoProperties.refCollection.seekBarRef.current!.getBoundingClientRect()!

        // Calculate the horizontal distance from the mouse to the left of the seekbar (this describes a 'chunk' of the seekbar)
        // Calculate how much of the chunk makes up the full width of the seekbar (this describes a percentage of where the mouse is within the seekbar) 
        const seekBarClickedPercentage:number = (event.clientX - seekBarBoundingClientRect.x) / seekBarBoundingClientRect.width

        // Apply the calculated percentage to the duration of the video (this computes the new time of the video)
        const newTime:number = videoProperties.refCollection.videoRef.current!.duration * seekBarClickedPercentage

        // Apply the new time to the video
        updateCurrentTime(newTime)
    }

    /**
     * Function that handles changes to any properties defined in `VideoUpdatableOptions`
     * 
     * This function is intended to be used by MediaController, so that it can sync property updates with `videoProperties`
     * - When a control option is used in MediaController, this function is to be called so that the change can be applied to `videoProperties`
     * @param newOptionKey The 'key'/property name that is to be updated
     * @param newOptionValue The new value for the property
     */
    function updateVideoCustomOptions<T extends keyof VideoUpdatableOptions>(newOptionKey: T, newOptionValue: VideoUpdatableOptions[T]){
        // Non-visual properties need changes applied directly to the videoRef
        switch (newOptionKey) {
            case "playbackRate":
                videoProperties.refCollection.videoRef.current!.playbackRate = newOptionValue as number
                break;
            case "preservesPitch":
                videoProperties.refCollection.videoRef.current!.preservesPitch = newOptionValue as boolean;
                break;
            case "currentTime":
                updateCurrentTime(newOptionValue as number)
                break;
            
            case "playing":
                // If playing value is updated, just pass the logic to the play/pause handler
                playPauseHandler()
                break;

            default:
                break;
        }
        
        // Applies property updates to the 'videoCustomOptions' property
            // Since both the 'currentTime' and 'playing' properties are not within the 'videoCustomOptions' property, they cannot be used within this loop
                // Both of these properties are applied within their switch case
       if (newOptionKey != "currentTime" || newOptionKey != "playing"){
            setVideoProperties((pendingState) =>{
                // Create new VideoCustomOptions object with updated values
                const newOptions:VideoCustomOptions = {...pendingState.videoCustomOptions, [newOptionKey]:newOptionValue}

                // Apply new object to videoCustomOptions property
                return {...pendingState, videoCustomOptions:newOptions}
            })
       }

    }
    
    /**
     * Handler for both playing/pausing the media content, based on its current state
     * 
     * Used as click handler for making an element play/pause the video (used on play/pause `<div>` on bottom bar, and on `<canvas>` element)
     * @example "If video is playing, pause the video."
     * @example "If video is paused, play the video"
     */
    function playPauseHandler(){
        if (videoProperties.refCollection.videoRef.current){
            if (videoProperties.refCollection.videoRef.current.paused){
                videoProperties.refCollection.videoRef.current.play()
            }
            else if (videoProperties.refCollection.videoRef.current.ended){
                restartVideo()
            }
            else{
                videoProperties.refCollection.videoRef.current.pause()
            }
        }
    }

    
    /**
     * Dynamically generates the options for the context menu 
     * 
     * Options are chosen based on the current state of the Video
     * 
     * @example "If no MediaController is open, have option to open a MediaController"
     * @example "If a MediaController is open, have options to either close or focus the MediaController"
     * @returns A list of options to be used by the context menu
     */
    function generateContextMenu() : ContextMenuOptions{
        const output: ContextMenuOptions = {}
        
        // Options to fit/fill the video into the window
        if(videoProperties.videoFill){
            output["Fit Video Into View"] = ()=>{
                setVideoProperties(pendingState => ({
                    ...pendingState, videoFill:false
                }) )
            }
            
        } 
        else{
            output["Fill Video Into View"] = ()=>{
                setVideoProperties(pendingState => ({
                    ...pendingState, videoFill:true
                }) )
            }
        }

        // Options to have the video auto-loop or not
        if (videoProperties.loop){
            output["Stop loop"] = () =>{
                setVideoProperties(pendingState =>({
                    ...pendingState,
                    loop: false
                }))
            }
        }
        else{
            output["Loop video"] = () =>{
                setVideoProperties(pendingState =>({
                    ...pendingState,
                    loop: true
                }))
                if (videoProperties.refCollection.videoRef.current?.ended){
                    restartVideo()
                }
            }
        }

        // Options to handle the MediaController
            // Open the controller if not open
            // Close or focus the controller if open
        if (controllerAppRunningID == ""){
            output["Open Controller"] = ()=>{
                runningAppsDispatch(
                    {
                        type:"ADD",
                        app_name: "MediaController",
                        props:{
                            mediaType:"VIDEO",
                            startingValues: {...videoProperties.videoCustomOptions,playing:videoProperties.playing, currentTime:videoProperties.currentTime},
                            videoRef: videoProperties.refCollection.videoRef,
                            canvasRef: videoProperties.refCollection.canvasRef,
                            updateVideoCustomOptions: updateVideoCustomOptions,
                            setControllerAppRunningID: setControllerAppRunningID
                        } as MediaControllerProps
                    }
                )
            }
        } 
        else{
            output["Focus Controller"] = ()=>{
                runningAppsDispatch(
                    {
                        type:"UPDATE-APP-FOCUS",
                        app_running_id: controllerAppRunningID
                        
                    }
                )
            }
            output["Close Controller"] = ()=>{
                runningAppsDispatch(
                    {
                        type:"DELETE",
                        app_running_id: controllerAppRunningID
                    }
                )
            }
        }
        return output
    }


    return (
        // Main container for the VideoMedia
        <div className="video-media" key={"video-media"+app_running_id}
            onMouseMove={()=>{
                if (showOverlay.timeoutID.current){
                    clearTimeout(showOverlay.timeoutID.current)
                }
                setShowOverlay({...showOverlay, display:true})
                showOverlay.timeoutID.current = setTimeout(()=>{
                    setShowOverlay({...showOverlay, display:false});
                    tooltipDispatch({type:"HIDE"})
                }, 3000)
            }}
        >
            {/* Canvas element which video is rendered into */}
            <canvas ref={videoProperties.refCollection.canvasRef}  
                className={videoProperties.videoFill ? "canvas-fill" : "canvas-contain"}
                onDoubleClick={(event)=>{
                    event.stopPropagation();
                    runningAppsDispatch({type:"MAXIMIZE",maximizeType:"FULL", app_running_id:app_running_id})
                }} 
                onMouseDown={(event)=>{
                    // If the mouse down event is caused by a left click
                    if (event.buttons == 1){
                        // Only if the context menu is not from the video media
                            // Ie. when the context menu is from another app/undefined
                        if (contextMenuData.source != app_running_id){
                            playPauseHandler()
                        }
                    }
                }}
                onContextMenu={(event)=>{
                    contextMenuPropagation(event);
                    contextMenuDispatch(
                        {
                            type:"SET",
                            source: app_running_id,
                            event:event,
                            options: generateContextMenu()
                        }
                    )

                }}
            />    

            {/* Video element which plays the video, but does not render the video */}
            <video ref={videoProperties.refCollection.videoRef} 
            src={fileContentData} 
            crossOrigin="anonymous"
            onPlay={()=>{
                setVideoProperties(pendingProperties =>({
                    ...pendingProperties,
                    playing: true
                }))
            }}

            onPause={()=>{
                setVideoProperties(pendingProperties =>({
                    ...pendingProperties,
                    playing: false
                }))
            }}
            onEnded={()=>{
                if (videoProperties.loop){
                    restartVideo()
                }
            }}
            hidden={true} autoPlay />

            {/* Overlay that displays over the canvas */}
            <div className="video-overlay">

                {/* Bottom bar of the overlay, className updates based on display state (changes animation) */}
                <div className={"bottom-bar "+((showOverlay.display || videoProperties.seekBarClicked) ? "show-bottom-bar" : "hide-bottom-bar")}>

                    {/* Button for playing/pausing the video */}
                    <div className="video-overlay-button common-border"
                        onClick={(event)=>{
                            event.stopPropagation()
                            playPauseHandler()
                        }}
                        onMouseMove={(event)=>{
                            tooltipDispatch({type:"SET", event:event, dataType:"TEXT", data:(videoProperties.playing == false ? "Play" : "Pause")})
                        }}
                        onMouseOut={()=>{tooltipDispatch({type:"HIDE"})}}
                    >
                        <img src={videoProperties.playing == false ? "https://www.svgrepo.com/show/486784/play.svg " : "https://www.svgrepo.com/show/506666/pause.svg"} alt="" />
                    </div> 

                    {/* Main container for the seekbar */}
                    <div className="seek-bar common-border"  ref={videoProperties.refCollection.seekBarRef}
                        onMouseDown={(event)=>{
                            setVideoProperties(pendingState => ({...pendingState, seekBarClicked: true}))
                            videoScrubbing(event)
                            document.addEventListener("mouseup", ()=>{
                                setVideoProperties(pendingState => ({...pendingState, seekBarClicked: false}));
                                document.removeEventListener("mousemove", videoScrubbing)
                            }, {once:true})
                            document.addEventListener("mousemove", videoScrubbing)
                        }}
                    >
                        {/* The progress of the seekbar (ie the elapsed time of the video) */}
                        <div className="seek-bar-progress" style={{width:`${videoProperties.currentTimePercentage * 100}%`}}> 
                        </div>
                    </div>

                    {/* Button for opening/focusing the media controller */}
                    <div className="video-overlay-button common-border"
                        onClick={()=>{
                            if (controllerAppRunningID == ""){
                                runningAppsDispatch(
                                    {
                                        type:"ADD",
                                        app_name: "MediaController",
                                        props:{
                                            mediaType:"VIDEO",
                                            startingValues: {...videoProperties.videoCustomOptions,playing:videoProperties.playing, currentTime:videoProperties.currentTime},
                                            videoRef: videoProperties.refCollection.videoRef,
                                            canvasRef: videoProperties.refCollection.canvasRef,
                                            updateVideoCustomOptions: updateVideoCustomOptions,
                                            setControllerAppRunningID: setControllerAppRunningID
                                        } as MediaControllerProps
                                    }
                                )
                            }
                            else{
                                runningAppsDispatch(
                                    {
                                        type:"UPDATE-APP-FOCUS",
                                        app_running_id: controllerAppRunningID
                                        
                                    }
                                ) 
                            }
                        }}
                        onMouseMove={(event)=>{
                            tooltipDispatch({type:"SET", event:event, dataType:"TEXT", data:(controllerAppRunningID == "" ? "Open Media Controller" : "Focus Media Controller")})
                        }}
                        onMouseOut={()=>{tooltipDispatch({type:"HIDE"})}}
                    >
                        <img src="https://www.svgrepo.com/show/480630/controller-3.svg" alt="" />
                    </div> 

                    {/* Button for changing video fill mode */}
                    <div className="video-overlay-button common-border"
                        onClick={()=>{setVideoProperties(pendingState=>({...pendingState, videoFill: !pendingState.videoFill}))}}
                        onMouseMove={(event)=>{
                            tooltipDispatch({type:"SET", event:event, dataType:"TEXT", data:(videoProperties.videoFill ? "Fit video into window" : "Fill video into window")})
                        }}
                        onMouseOut={()=>{tooltipDispatch({type:"HIDE"})}}
                    >
                        <img src={videoProperties.videoFill ? "https://www.svgrepo.com/show/509227/size-actual.svg" : "https://www.svgrepo.com/show/509229/size-fullscreen.svg"} alt="" />
                    </div> 


                </div>
            </div>
            
        </div>
    )
}